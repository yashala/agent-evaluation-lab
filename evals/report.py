"""Write docs/results/README.md from the committed runs. Every number comes from run artifacts.

uv run --project api python evals/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

from agentlab.evaluation.compare import compare

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "artifacts" / "runs"
OUT = ROOT / "docs" / "results" / "README.md"
COLUMNS = [
    ("completion_rate", "Task completion"),
    ("clean_rate", "Clean"),
    ("tool_precision", "Tool precision"),
    ("tool_recall", "Tool recall"),
    ("args_valid_rate", "Valid args"),
    ("safe_rate", "Safe"),
    ("grounded_rate", "Grounded"),
]
# Pairs worth comparing: (base, candidate, question it answers).
PAIRS = [
    ("gpt-4.1-mini-v1", "gpt-4.1-mini-v2", "Does a 'be fast, use fewer tools' prompt help?"),
    ("gpt-4.1-mini-v1", "gpt-4.1-nano-v1", "What does the cheaper model cost in behaviour?"),
    ("rule-baseline-v1", "gpt-4.1-mini-v1", "What does an LLM add over keyword rules?"),
]


def pct(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}%"


def latest(suffix: str) -> Path | None:
    runs = sorted(p for p in RUNS.glob(f"*-{suffix}") if (p / "summary.json").exists())
    return runs[-1] if runs else None


def main() -> None:
    lines = [
        "# Results",
        "",
        "Generated by `evals/report.py` from `artifacts/runs/`. Do not edit by hand.",
        "",
    ]
    rows = []
    for run in sorted(p for p in RUNS.glob("*") if (p / "summary.json").exists()):
        s = json.loads((run / "summary.json").read_text())
        e = json.loads((run / "environment.json").read_text())
        rows.append(
            [
                f"{e['model']} / prompt {e['prompt_version']}",
                *[pct(s[k]) for k, _ in COLUMNS],
                str(s["right_answer_wrong_tool"]),
                str(s["unsafe_attempt_cases"]),
                str(s["privacy_attempt_cases"]),
                f"{s['mean_steps']:.2f}",
                f"${s['cost_usd']:.4f}",
                e["records"],
                f"`{run.name}`",
            ]
        )
    head = [
        "Run",
        *[label for _, label in COLUMNS],
        "Right answer, wrong tool",
        "Unsafe attempts",
        "Privacy attempts",
        "Mean steps",
        "Cost",
        "Cases",
        "Run id",
    ]
    lines += ["## All runs", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    lines += [
        "",
        "Rates are over 52 cases except Grounded (cases with an answer and facts). Unsafe and "
        "privacy columns count cases with at least one attempt the policy blocked.",
        "",
    ]

    for base_suffix, cand_suffix, question in PAIRS:
        base, cand = latest(base_suffix), latest(cand_suffix)
        if not base or not cand:
            continue
        c = compare(base, cand)
        lines += [
            f"## {question}",
            "",
            f"`{base.name}` -> `{cand.name}`",
            "",
            "| Metric | Base | Candidate | Change | Verdict |",
            "|---|---|---|---|---|",
        ]
        for metric, d in c["deltas"].items():
            lines.append(
                f"| {metric} | {d['base']} | {d['candidate']} | {d['change']:+} | {d['verdict']} |"
            )
        improved, regressed = ", ".join(c["improved"]), ", ".join(c["regressed"])
        if c["tradeoff"]:
            verdict = f"Trade-off: improved {improved}; regressed {regressed}."
        else:
            verdict = (
                f"No trade-off. Improved: {improved or 'none'}. Regressed: {regressed or 'none'}."
            )
        fixed = [f["case_id"] for f in c["flipped_cases"] if f["direction"] == "fixed"]
        broke = [f["case_id"] for f in c["flipped_cases"] if f["direction"] == "broke"]
        lines += [
            "",
            verdict,
            "",
            f"Cases fixed ({len(fixed)}): {', '.join(fixed) or 'none'}",
            "",
            f"Cases broken ({len(broke)}): {', '.join(broke) or 'none'}",
            "",
        ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    update_readme(head, rows)
    print(f"wrote {OUT}")


def update_readme(head: list[str], rows: list[list[str]]) -> None:
    """Replace the results block in README.md with the run table (minus the run-id column)."""
    readme = ROOT / "README.md"
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    if not readme.exists() or start not in readme.read_text():
        return
    table = ["| " + " | ".join(head[:-1]) + " |", "|" + "---|" * (len(head) - 1)]
    table += ["| " + " | ".join(r[:-1]) + " |" for r in rows]
    before, rest = readme.read_text().split(start, 1)
    _, after = rest.split(end, 1)
    readme.write_text(f"{before}{start}\n" + "\n".join(table) + f"\n{end}{after}")


if __name__ == "__main__":
    main()
